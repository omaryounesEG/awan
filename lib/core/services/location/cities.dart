import 'package:awan/core/services/location/app_location.dart';

/// Offline city picker — no geocoding call, works on a plane.
///
/// Prayer times only need coordinates; the names are for the human.
class CityPreset {
  const CityPreset({
    required this.nameAr,
    required this.nameEn,
    required this.countryAr,
    required this.countryEn,
    required this.latitude,
    required this.longitude,
    required this.method,
  });

  final String nameAr;
  final String nameEn;
  final String countryAr;
  final String countryEn;
  final double latitude;
  final double longitude;

  /// Sensible default calculation method for this city/authority.
  final String method;

  AppLocation toLocation() => AppLocation(
        latitude: latitude,
        longitude: longitude,
        cityAr: nameAr,
        cityEn: nameEn,
      );
}

