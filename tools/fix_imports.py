"""Normalise every project import to `package:awan/...`.

Skips `lib/l10n/*` (files generated by `flutter gen-l10n`, which use relative
imports by design) and untouched platform/dart imports.

Run from the project root: python tools/fix_imports.py
"""
import pathlib
import re

LIB = pathlib.Path("lib")
PATTERN = re.compile(r"""^\s*(import|export)\s+'([^']+)'(.*)$""")

changed = 0
for path in LIB.rglob("*.dart"):
    if path.parent.name == "l10n":
        continue
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
    dirty = False
    out = []
    for line in lines:
        match = PATTERN.match(line)
        if not match:
            out.append(line)
            continue
        keyword, target, tail = match.groups()
        if target.startswith("dart:") or target.startswith("package:"):
            out.append(line)
            continue
        resolved = (path.parent / target).resolve()
        if not resolved.exists():
            out.append(line)
            print("!! unresolved:", path.as_posix(), "->", target)
            continue
        try:
            rel = resolved.relative_to(LIB.resolve()).as_posix()
        except ValueError:
            out.append(line)
            continue
        out.append("{} 'package:awan/{}'{}\n".format(keyword, rel, tail))
        dirty = True
    if dirty:
        path.write_text("".join(out), encoding="utf-8")
        changed += 1

print("normalised", changed, "files")
